#!/usr/bin/env python3
"""
ETM multi-agent coordinator.  Stdlib only, Python 3.9+.

Lets several AI agents (and humans) work on Enter The Matricks at the same time
without stepping on each other.  Source of truth lives in this tracker repo:

  tracking/tasks/T-XXXX.json    one file per task (status, deps, owned paths)
  tracking/claims/T-XXXX.json   a claim = a lock. Exists only while someone works on the task
  tracking/reports/*.md         one file per activity entry (never edited, so never conflicts)
  BOARD.md, ACTIVITY_REPORT.md, RESUME_HERE.md (auto section)  -> generated by `render`

Typical loop for an agent (see AGENTS.md):
  python3 tools/agent.py sync
  python3 tools/agent.py next   --agent claude-a
  python3 tools/agent.py claim  T-0007 --agent claude-a --push
  ... work in the game repo, commit with "[T-0007] ..." ...
  python3 tools/agent.py complete T-0007 --agent claude-a --summary "..." --commits abc123 --push

Identity: --agent NAME or env ETM_AGENT.
"""
from __future__ import annotations

import argparse
import datetime as dt
import fnmatch
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TASKS = ROOT / "tracking" / "tasks"
CLAIMS = ROOT / "tracking" / "claims"
REPORTS = ROOT / "tracking" / "reports"
CONFIG = ROOT / "etm.config.json"

STATUSES = ["todo", "in_progress", "review", "blocked", "done"]
REQUIRED = ["id", "title", "milestone", "area", "repo", "status", "priority",
            "depends_on", "paths", "acceptance", "description"]
ID_RE = re.compile(r"^T-\d{4}$")
AUTO_START = "<!-- AUTO:START (generated by tools/agent.py render; do not edit inside) -->"
AUTO_END = "<!-- AUTO:END -->"


# ---------------------------------------------------------------- utilities
def now() -> str:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def parse_time(s: str) -> dt.datetime:
    return dt.datetime.fromisoformat(s.replace("Z", "+00:00"))


def config() -> dict:
    cfg = {"game_repo_path": "../enter-the-matricks", "stale_hours": 24, "review_required": True}
    if CONFIG.exists():
        cfg.update(json.loads(CONFIG.read_text()))
    return cfg


def die(msg: str, code: int = 1):
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(code)


def agent_name(args) -> str:
    name = getattr(args, "agent", None) or os.environ.get("ETM_AGENT")
    if not name:
        die("agent identity required: pass --agent NAME or set ETM_AGENT")
    if not re.match(r"^[A-Za-z0-9._-]{2,40}$", name):
        die("agent name may only contain letters, digits, . _ - (2-40 chars)")
    return name


def read_json(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


def write_json(p: Path, data: dict):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def load_tasks() -> dict[str, dict]:
    return {p.stem: read_json(p) for p in sorted(TASKS.glob("T-*.json"))}


def load_claims() -> dict[str, dict]:
    return {p.stem: read_json(p) for p in sorted(CLAIMS.glob("T-*.json"))}


def task_or_die(tasks, tid) -> dict:
    tid = tid.upper()
    if tid not in tasks:
        die(f"unknown task {tid}")
    return tasks[tid]


def git(*a, cwd=ROOT, check=True) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *a], cwd=cwd, text=True, capture_output=True, check=check)


def in_git() -> bool:
    return git("rev-parse", "--is-inside-work-tree", check=False).returncode == 0


# ------------------------------------------------------------ path locking
def _prefix(pattern: str) -> str:
    """Literal directory/file prefix of a glob, e.g. 'Source/ETM/Weapons/**' -> 'Source/ETM/Weapons/'."""
    cut = len(pattern)
    for ch in "*?[":
        i = pattern.find(ch)
        if i != -1:
            cut = min(cut, i)
    return pattern[:cut]


def patterns_overlap(a: str, b: str) -> bool:
    """Conservative: two path globs overlap if either literal prefix contains the other,
    or one matches the other literally. False positives are acceptable (safer); false
    negatives are not."""
    pa, pb = _prefix(a), _prefix(b)
    if pa.startswith(pb) or pb.startswith(pa):
        return True
    return fnmatch.fnmatch(a, b) or fnmatch.fnmatch(b, a)


def path_matches(path: str, pattern: str) -> bool:
    if pattern.endswith("/**"):
        return path.startswith(pattern[:-2]) or path == pattern[:-3]
    return fnmatch.fnmatch(path, pattern)


def conflicts_for(task: dict, tasks: dict, claims: dict, me: str | None = None) -> list[str]:
    """Return a list of human-readable conflicts between `task` and active claims."""
    out = []
    for tid, c in claims.items():
        if tid == task["id"]:
            continue
        other = tasks.get(tid)
        if not other or other["repo"] != task["repo"]:
            continue
        for pa in task["paths"]:
            for pb in other["paths"]:
                if patterns_overlap(pa, pb):
                    out.append(f"{tid} ({c['agent']}) owns '{pb}' which overlaps '{pa}'")
    return out


# ---------------------------------------------------------------- readiness
def deps_done(task, tasks) -> list[str]:
    return [d for d in task["depends_on"] if tasks.get(d, {}).get("status") != "done"]


def ready_tasks(tasks, claims):
    out = []
    for t in tasks.values():
        if t["status"] != "todo" or t["id"] in claims:
            continue
        if deps_done(t, tasks):
            continue
        if conflicts_for(t, tasks, claims):
            continue
        out.append(t)
    return sorted(out, key=lambda t: (t["priority"], t["milestone"], t["id"]))


def is_stale(claim: dict, hours: float) -> bool:
    return (dt.datetime.now(dt.timezone.utc) - parse_time(claim["heartbeat"])).total_seconds() > hours * 3600


# ------------------------------------------------------------- git helpers
def commit_tracking(message: str, push: bool):
    if not in_git():
        print("(not a git repo: skipped commit)")
        return
    git("add", "-A", "tracking", "BOARD.md", "ACTIVITY_REPORT.md", "RESUME_HERE.md")
    if git("diff", "--cached", "--quiet", check=False).returncode == 0:
        print("(nothing new to commit)")
    else:
        git("commit", "-m", message)
        print(f"committed: {message}")
    if push and unpushed_commits():
        push_with_retry()


def unpushed_commits() -> int:
    r = git("rev-list", "--count", "@{u}..HEAD", check=False)
    return int(r.stdout.strip() or 0) if r.returncode == 0 else 1


GENERATED = ["BOARD.md", "ACTIVITY_REPORT.md", "RESUME_HERE.md"]


def rebase_onto_remote() -> bool:
    """git pull --rebase, auto-resolving conflicts that touch ONLY generated files
    (they are re-rendered from tasks/claims/reports). Returns False on a real conflict
    (claims/tasks/reports), after aborting the rebase."""
    r = git("pull", "--rebase", check=False)
    for _ in range(50):
        if r.returncode == 0:
            return True
        conflicted = git("diff", "--name-only", "--diff-filter=U", check=False).stdout.split()
        if not conflicted or not set(conflicted) <= set(GENERATED):
            git("rebase", "--abort", check=False)
            return False
        for f in conflicted:
            git("checkout", "--theirs", "--", f, check=False)
        render(quiet=True)
        git("add", *GENERATED)
        r = subprocess.run(["git", "-c", "core.editor=true", "rebase", "--continue"],
                           cwd=ROOT, text=True, capture_output=True)
    git("rebase", "--abort", check=False)
    return False


def lost_race(reason: str):
    """Drop our unpushed tracking commit(s) and match the remote, so the local board
    never shows a claim we don't actually hold."""
    git("fetch", check=False)
    git("reset", "--hard", "@{u}", check=False)
    die(reason + "\nYour local tracker was reset to the remote state. "
        "Run `python3 tools/agent.py next` and pick another task.")


def push_with_retry(attempts: int = 3):
    """Push; on rejection rebase (auto-fixing generated files) and retry. A real conflict
    (e.g. two agents claimed the same task) means we lost the race: reset and stop."""
    for i in range(attempts):
        r = git("push", "origin", "HEAD", check=False)
        if r.returncode == 0:
            print("pushed" + (" (after rebase)" if i else ""))
            return
        print("push rejected, rebasing on remote...")
        if not rebase_onto_remote():
            lost_race("conflict: another agent changed the same task or claim at the same time.")
        render(quiet=True)
        git("add", *GENERATED)
        if git("diff", "--cached", "--quiet", check=False).returncode != 0:
            git("commit", "-m", "chore(tracking): re-render after rebase")
        # A rebase can land another agent's claim on our task. Validate before retrying.
        errs = [e for e in validate() if "path overlap" in e or "no such task" in e]
        if errs:
            lost_race("after merging remote state: " + "; ".join(errs))
    lost_race(f"push failed {attempts} times: " + r.stderr.strip())


# ---------------------------------------------------------------- reports
def write_report(agent: str, task_id: str | None, kind: str, text: str, extra: dict | None = None):
    ts = now()
    safe = ts.replace(":", "").replace("-", "")
    name = f"{safe}_{agent}_{task_id or 'general'}_{kind}.md"
    lines = [f"---", f"time: {ts}", f"agent: {agent}", f"task: {task_id or '-'}", f"kind: {kind}"]
    for k, v in (extra or {}).items():
        lines.append(f"{k}: {v}")
    lines += ["---", "", text.strip(), ""]
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / name).write_text("\n".join(lines), encoding="utf-8")


def read_reports():
    out = []
    for p in sorted(REPORTS.glob("*.md")):
        raw = p.read_text(encoding="utf-8")
        m = re.match(r"---\n(.*?)\n---\n(.*)", raw, re.S)
        if not m:
            continue
        meta = dict(line.split(": ", 1) for line in m.group(1).splitlines() if ": " in line)
        meta["body"] = m.group(2).strip()
        out.append(meta)
    return sorted(out, key=lambda r: r.get("time", ""), reverse=True)


# ----------------------------------------------------------------- render
def board_text(tasks, claims) -> str:
    cfg = config()
    lines = ["# Task Board", "", f"_Generated {now()} by `tools/agent.py render`. Do not edit by hand._", ""]
    counts = {s: sum(1 for t in tasks.values() if t["status"] == s) for s in STATUSES}
    total = len(tasks) or 1
    pct = round(100 * counts["done"] / total)
    lines.append(f"**Progress:** {counts['done']}/{len(tasks)} done ({pct}%) · "
                 + " · ".join(f"{s}: {counts[s]}" for s in STATUSES))
    lines.append("")
    ms = sorted({t["milestone"] for t in tasks.values()})
    lines.append("| Milestone | Done | Total | Progress |")
    lines.append("|---|---:|---:|---|")
    for m in ms:
        mt = [t for t in tasks.values() if t["milestone"] == m]
        d = sum(1 for t in mt if t["status"] == "done")
        bar = "█" * round(10 * d / len(mt)) + "░" * (10 - round(10 * d / len(mt)))
        lines.append(f"| {m} | {d} | {len(mt)} | `{bar}` |")
    lines.append("")
    lines.append("## Active claims")
    lines.append("")
    if claims:
        lines.append("| Task | Agent | Since | Last heartbeat | Stale? |")
        lines.append("|---|---|---|---|---|")
        for tid, c in claims.items():
            st = "⚠ STALE" if is_stale(c, cfg["stale_hours"]) else ""
            lines.append(f"| {tid} {tasks.get(tid, {}).get('title', '?')} | {c['agent']} | {c['claimed_at']} | {c['heartbeat']} | {st} |")
    else:
        lines.append("_None. Every task is free._")
    lines.append("")
    ready = {t["id"] for t in ready_tasks(tasks, claims)}
    for s in ["in_progress", "review", "blocked", "todo", "done"]:
        group = [t for t in tasks.values() if t["status"] == s]
        if not group:
            continue
        lines.append(f"## {s.replace('_', ' ').title()} ({len(group)})")
        lines.append("")
        lines.append("| ID | P | Milestone | Area | Repo | Title | Depends on | Owner |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for t in sorted(group, key=lambda t: (t["milestone"], t["priority"], t["id"])):
            tag = " 🟢 ready" if t["id"] in ready else ""
            owner = claims.get(t["id"], {}).get("agent") or t.get("assignee") or ""
            lines.append(f"| {t['id']}{tag} | {t['priority']} | {t['milestone']} | {t['area']} | {t['repo']} | "
                         f"{t['title']} | {', '.join(t['depends_on']) or '-'} | {owner} |")
        lines.append("")
    return "\n".join(lines)


def activity_text(limit=40) -> str:
    reps = read_reports()
    lines = ["# Activity Report", "",
             "_Brief log of what happened, newest first. Generated from `tracking/reports/`. "
             "Add entries with `tools/agent.py log` or `complete`._", ""]
    if not reps:
        lines.append("_No activity yet._")
    for r in reps[:limit]:
        head = f"- **{r.get('time', '')[:16].replace('T', ' ')}Z** · `{r.get('agent')}` · {r.get('task')} · _{r.get('kind')}_"
        if r.get("commits"):
            head += f" · commits: {r['commits']}"
        lines.append(head)
        for bl in r["body"].splitlines():
            if bl.strip():
                lines.append(f"  {bl}")
    if len(reps) > limit:
        lines += ["", f"_{len(reps) - limit} older entries in `tracking/reports/`._"]
    return "\n".join(lines) + "\n"


def resume_auto(tasks, claims) -> str:
    ready = ready_tasks(tasks, claims)[:5]
    reps = read_reports()[:5]
    done = sum(1 for t in tasks.values() if t["status"] == "done")
    current_ms = next((m for m in sorted({t['milestone'] for t in tasks.values()})
                       if any(t["status"] != "done" for t in tasks.values() if t["milestone"] == m)), "all done")
    lines = [AUTO_START, "", f"**Snapshot {now()}** · {done}/{len(tasks)} tasks done · current milestone: **{current_ms}**", ""]
    lines.append("**In flight:** " + (", ".join(f"{t} ({c['agent']})" for t, c in claims.items()) or "nothing"))
    review = [t["id"] for t in tasks.values() if t["status"] == "review"]
    blocked = [t["id"] for t in tasks.values() if t["status"] == "blocked"]
    lines.append(f"**Awaiting review:** {', '.join(review) or 'none'} · **Blocked:** {', '.join(blocked) or 'none'}")
    lines.append("")
    lines.append("**Next ready tasks (pick the top one you can do):**")
    for t in ready:
        lines.append(f"1. `{t['id']}` [{t['milestone']}, P{t['priority']}, {t['repo']}] {t['title']}")
    if not ready:
        lines.append("_None ready. Review `review` tasks or unblock `blocked` ones._")
    lines.append("")
    lines.append("**Last activity:**")
    for r in reps:
        first = r["body"].splitlines()[0] if r["body"] else ""
        lines.append(f"- {r.get('time', '')[:16]}Z `{r.get('agent')}` {r.get('task')}: {first}")
    lines += ["", AUTO_END]
    return "\n".join(lines)


def render(quiet=False):
    tasks, claims = load_tasks(), load_claims()
    (ROOT / "BOARD.md").write_text(board_text(tasks, claims) + "\n", encoding="utf-8")
    (ROOT / "ACTIVITY_REPORT.md").write_text(activity_text(), encoding="utf-8")
    rp = ROOT / "RESUME_HERE.md"
    if rp.exists():
        s = rp.read_text(encoding="utf-8")
        if AUTO_START in s and AUTO_END in s:
            pre, rest = s.split(AUTO_START, 1)
            _, post = rest.split(AUTO_END, 1)
            rp.write_text(pre + resume_auto(tasks, claims) + post, encoding="utf-8")
    if not quiet:
        print("rendered BOARD.md, ACTIVITY_REPORT.md, RESUME_HERE.md")


# --------------------------------------------------------------- validate
def validate(strict_stale=False) -> list[str]:
    errs = []
    tasks, claims = load_tasks(), load_claims()
    cfg = config()
    for tid, t in tasks.items():
        for k in REQUIRED:
            if k not in t:
                errs.append(f"{tid}: missing field '{k}'")
        if t.get("id") != tid:
            errs.append(f"{tid}: id field '{t.get('id')}' != filename")
        if not ID_RE.match(tid):
            errs.append(f"{tid}: bad id format")
        if t.get("status") not in STATUSES:
            errs.append(f"{tid}: bad status '{t.get('status')}'")
        if t.get("repo") not in ("game", "tracker"):
            errs.append(f"{tid}: repo must be 'game' or 'tracker'")
        if t.get("priority") not in (1, 2, 3):
            errs.append(f"{tid}: priority must be 1, 2 or 3")
        if not t.get("paths"):
            errs.append(f"{tid}: paths must list at least one owned path")
        if not t.get("acceptance"):
            errs.append(f"{tid}: acceptance criteria required")
        for d in t.get("depends_on", []):
            if d not in tasks:
                errs.append(f"{tid}: depends on unknown {d}")
        if t.get("status") == "done" and deps_done(t, tasks):
            errs.append(f"{tid}: done but dependencies not done: {deps_done(t, tasks)}")
        if t.get("status") == "in_progress" and tid not in claims:
            errs.append(f"{tid}: in_progress without a claim")
    # cycles
    state = {}

    def visit(n, stack):
        if state.get(n) == 1:
            errs.append(f"dependency cycle: {' -> '.join(stack + [n])}")
            return
        if state.get(n) == 2 or n not in tasks:
            return
        state[n] = 1
        for d in tasks[n].get("depends_on", []):
            visit(d, stack + [n])
        state[n] = 2

    for n in tasks:
        visit(n, [])
    for tid, c in claims.items():
        if tid not in tasks:
            errs.append(f"claim {tid}: no such task")
            continue
        if tasks[tid]["status"] in ("done", "todo"):
            errs.append(f"claim {tid}: task status is {tasks[tid]['status']} but a claim exists")
        if strict_stale and is_stale(c, cfg["stale_hours"]):
            errs.append(f"claim {tid}: stale (no heartbeat for >{cfg['stale_hours']}h, agent {c['agent']})")
        for msg in conflicts_for(tasks[tid], tasks, claims):
            errs.append(f"claim {tid}: path overlap with {msg}")
    return errs


# ---------------------------------------------------------------- commands
def cmd_status(a):
    tasks, claims = load_tasks(), load_claims()
    print(board_text(tasks, claims))


def cmd_next(a):
    tasks, claims = load_tasks(), load_claims()
    me = agent_name(a)
    mine = [t for t, c in claims.items() if c["agent"] == me]
    if mine:
        print(f"You already hold: {', '.join(mine)}. Finish or release those first (one task at a time).")
    rs = ready_tasks(tasks, claims)
    if a.area:
        rs = [t for t in rs if t["area"] == a.area]
    if a.repo:
        rs = [t for t in rs if t["repo"] == a.repo]
    if not rs:
        print("No ready tasks. Check `review` tasks (review another agent's work) or `blocked` ones.")
        return
    for t in rs[: a.n]:
        print(f"{t['id']}  P{t['priority']}  {t['milestone']:<4} {t['area']:<12} [{t['repo']}] {t['title']}")


def cmd_show(a):
    tasks, claims = load_tasks(), load_claims()
    t = task_or_die(tasks, a.task)
    print(json.dumps(t, indent=2, ensure_ascii=False))
    if t["id"] in claims:
        print("claim:", json.dumps(claims[t["id"]]))
    missing = deps_done(t, tasks)
    if missing:
        print("waiting on:", ", ".join(missing))


def cmd_claim(a):
    me = agent_name(a)
    if a.push and in_git() and not rebase_onto_remote():
        lost_race("your unpushed tracker commits conflict with the remote (stale claim?).")
    tasks, claims = load_tasks(), load_claims()
    t = task_or_die(tasks, a.task)
    tid = t["id"]
    cfg = config()
    if tid in claims:
        c = claims[tid]
        if c["agent"] == me:
            die(f"you already hold {tid}")
        if not (a.force and is_stale(c, cfg["stale_hours"])):
            die(f"{tid} is claimed by {c['agent']} (heartbeat {c['heartbeat']}). "
                f"Use --force only if the claim is stale (> {cfg['stale_hours']}h).")
        print(f"taking over stale claim from {c['agent']}")
        write_report(me, tid, "takeover", f"Took over stale claim from {c['agent']}.")
    if t["status"] not in ("todo", "blocked") and not a.force:
        die(f"{tid} has status '{t['status']}', not claimable")
    missing = deps_done(t, tasks)
    if missing:
        die(f"{tid} depends on unfinished tasks: {', '.join(missing)}")
    held = [x for x, c in claims.items() if c["agent"] == me and x != tid]
    if held and not a.allow_multiple:
        die(f"you already hold {', '.join(held)}. Finish or release it first, or pass --allow-multiple")
    conf = conflicts_for(t, tasks, {k: v for k, v in claims.items() if k != tid})
    if conf:
        die("path conflict, so another agent owns overlapping files:\n  " + "\n  ".join(conf))
    branch = f"agent/{me}/{tid.lower()}"
    write_json(CLAIMS / f"{tid}.json", {"task": tid, "agent": me, "claimed_at": now(),
                                        "heartbeat": now(), "branch": branch, "note": a.note or ""})
    t["status"] = "in_progress"
    t["assignee"] = me
    t.setdefault("history", []).append({"time": now(), "agent": me, "event": "claimed"})
    write_json(TASKS / f"{tid}.json", t)
    write_report(me, tid, "claim", a.note or f"Claimed {tid}: {t['title']}")
    render(quiet=True)
    commit_tracking(f"[{tid}] claim by {me}", a.push)
    print(f"\nClaimed {tid}. Work on branch '{branch}' in the {t['repo']} repo.")
    print("You own these paths (stay inside them):")
    for p in t["paths"]:
        print(f"  {p}")
    print("Acceptance:")
    for x in t["acceptance"]:
        print(f"  - {x}")


def _require_claim(tid, me, claims):
    if tid not in claims:
        die(f"{tid} is not claimed")
    if claims[tid]["agent"] != me:
        die(f"{tid} is claimed by {claims[tid]['agent']}, not you")


def cmd_heartbeat(a):
    me = agent_name(a)
    claims = load_claims()
    tid = a.task.upper()
    _require_claim(tid, me, claims)
    c = claims[tid]
    c["heartbeat"] = now()
    if a.note:
        c["note"] = a.note
        write_report(me, tid, "progress", a.note)
    write_json(CLAIMS / f"{tid}.json", c)
    render(quiet=True)
    commit_tracking(f"[{tid}] heartbeat {me}", a.push)


def cmd_release(a):
    me = agent_name(a)
    tasks, claims = load_tasks(), load_claims()
    t = task_or_die(tasks, a.task)
    tid = t["id"]
    _require_claim(tid, me, claims)
    (CLAIMS / f"{tid}.json").unlink()
    t["status"] = "blocked" if a.blocked else "todo"
    t["assignee"] = None
    t.setdefault("history", []).append({"time": now(), "agent": me,
                                        "event": "blocked" if a.blocked else "released", "reason": a.reason})
    if a.blocked:
        t["blocked_reason"] = a.reason
    write_json(TASKS / f"{tid}.json", t)
    write_report(me, tid, "blocked" if a.blocked else "release", a.reason or "Released.")
    render(quiet=True)
    commit_tracking(f"[{tid}] {'blocked' if a.blocked else 'release'} by {me}", a.push)


def cmd_complete(a):
    me = agent_name(a)
    tasks, claims = load_tasks(), load_claims()
    t = task_or_die(tasks, a.task)
    tid = t["id"]
    _require_claim(tid, me, claims)
    cfg = config()
    (CLAIMS / f"{tid}.json").unlink()
    t["status"] = "review" if cfg["review_required"] and not a.no_review else "done"
    t["assignee"] = me
    t["result"] = {"summary": a.summary, "commits": a.commits or "", "verification": a.verified or "",
                   "remaining": a.remaining or "", "next": a.next or "", "completed_at": now()}
    t.setdefault("history", []).append({"time": now(), "agent": me, "event": "completed"})
    write_json(TASKS / f"{tid}.json", t)
    body = [a.summary]
    if a.verified:
        body.append(f"Verified: {a.verified}")
    if a.remaining:
        body.append(f"Remaining: {a.remaining}")
    if a.next:
        body.append(f"Next: {a.next}")
    write_report(me, tid, "complete", "\n".join(body), {"commits": a.commits or "-"})
    render(quiet=True)
    commit_tracking(f"[{tid}] complete by {me} -> {t['status']}", a.push)
    print(f"{tid} -> {t['status']}")


def cmd_review(a):
    me = agent_name(a)
    tasks = load_tasks()
    t = task_or_die(tasks, a.task)
    tid = t["id"]
    if t["status"] != "review":
        die(f"{tid} is '{t['status']}', not in review")
    if t.get("assignee") == me and not a.self_ok:
        die("you can't approve your own work (pass --self-ok only if you're the only agent)")
    t["status"] = "done" if a.approve else "todo"
    t.setdefault("history", []).append({"time": now(), "agent": me,
                                        "event": "approved" if a.approve else "changes_requested",
                                        "note": a.note})
    write_json(TASKS / f"{tid}.json", t)
    write_report(me, tid, "review", ("Approved. " if a.approve else "Changes requested. ") + (a.note or ""))
    render(quiet=True)
    commit_tracking(f"[{tid}] review by {me}: {'approved' if a.approve else 'changes requested'}", a.push)


def cmd_log(a):
    me = agent_name(a)
    write_report(me, a.task.upper() if a.task else None, a.kind, a.message)
    render(quiet=True)
    commit_tracking(f"[{a.task.upper() if a.task else 'log'}] note by {me}", a.push)


def cmd_add(a):
    tasks = load_tasks()
    n = max([int(t[2:]) for t in tasks] or [0]) + 1
    tid = f"T-{n:04d}"
    t = {"id": tid, "title": a.title, "milestone": a.milestone, "area": a.area, "repo": a.repo,
         "status": "todo", "priority": a.priority, "depends_on": a.depends or [], "paths": a.paths,
         "acceptance": a.acceptance, "description": a.description or "", "assignee": None, "history": []}
    write_json(TASKS / f"{tid}.json", t)
    errs = [e for e in validate() if e.startswith(tid)]
    if errs:
        (TASKS / f"{tid}.json").unlink()
        die("; ".join(errs))
    render(quiet=True)
    commit_tracking(f"[{tid}] add task", a.push)
    print(tid)


def cmd_check_staged(a):
    """Used by the game repo's pre-commit hook: every staged file must be inside a path
    owned by a task this agent holds."""
    me = agent_name(a)
    tasks, claims = load_tasks(), load_claims()
    mine = [tasks[t] for t, c in claims.items() if c["agent"] == me and t in tasks and tasks[t]["repo"] == a.repo]
    if not mine:
        die(f"agent '{me}' holds no claimed '{a.repo}' task. Claim one before committing "
            f"(tracker: python3 tools/agent.py next --agent {me})")
    repo_dir = Path(a.dir) if a.dir else (ROOT / config()["game_repo_path"])
    repo_dir = repo_dir.resolve()
    staged = git("diff", "--cached", "--name-only", cwd=repo_dir).stdout.split()
    allowed_always = [".gitignore", ".gitattributes"]
    bad = [f for f in staged if f not in allowed_always
           and not any(path_matches(f, p) for t in mine for p in t["paths"])]
    if bad:
        die("these staged files are outside your claimed task paths:\n  " + "\n  ".join(bad)
            + "\nYour paths: " + ", ".join(p for t in mine for p in t["paths"])
            + "\nEither unstage them, or claim/add a task that owns them.")
    print(f"ok: {len(staged)} staged file(s) within {', '.join(t['id'] for t in mine)}")


def cmd_validate(a):
    errs = validate(strict_stale=a.strict)
    if errs:
        print("\n".join(errs))
        sys.exit(1)
    print(f"ok: {len(load_tasks())} tasks, {len(load_claims())} claims, no problems")


